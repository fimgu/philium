// Real rendered product components with fixture IPC. Not native acceptance.
export async function checkCodeGraph(page, shot) {
  const errors = [];
  const wait = () => new Promise((r) => setTimeout(r, 220));
  const click = async (selector, text) => page.evaluate((selector, text) => {
    const item = [...document.querySelectorAll(selector)].find((n) => n.textContent.includes(text));
    item?.click(); return !!item;
  }, selector, text);
  const target = async (value) => {
    const ok = await page.evaluate((value) => {
      const select = [...document.querySelectorAll('.code-bar select')].find((s) => [...s.options].some((o) => o.value === 'local'));
      if (!select) return false;
      select.value = value; select.dispatchEvent(new Event('change', { bubbles: true })); return true;
    }, value);
    if (!ok) errors.push('target selector missing');
    await wait();
  };
  await click('.nav-item', 'Agents'); await wait();
  await page.waitForSelector('.composer textarea');
  await page.$eval('.composer textarea', (el) => { el.value = 'My existing instructions'; el.dispatchEvent(new Event('input', { bubbles: true })); });
  await click('.nav-item', 'Code'); await wait();
  await click('.code-bar button', 'Graph');
  await page.waitForSelector('.pgraph canvas');
  await wait();
  const zoom = await page.evaluate(async () => {
    const c = document.querySelector('.pgraph canvas'), r = c.getBoundingClientRect();
    const before = c.__graphScale;
    c.dispatchEvent(new WheelEvent('wheel', { deltaY: -12.5, deltaX: 1, deltaMode: 0, clientX: r.x + r.width / 2, clientY: r.y + r.height / 2, bubbles: true, cancelable: true }));
    await new Promise((resolve) => setTimeout(resolve, 70));
    const after = c.__graphScale;
    c.dispatchEvent(new WheelEvent('wheel', { deltaY: 12.5, deltaMode: 0, clientX: r.x + r.width / 2, clientY: r.y + r.height / 2, bubbles: true, cancelable: true }));
    await new Promise((resolve) => setTimeout(resolve, 70));
    return { before, after, back: c.__graphScale };
  });
  if (!(zoom.after > zoom.before && Math.abs(zoom.back - zoom.before) < 1e-6)) errors.push(`trackpad scroll did not zoom reversibly: ${JSON.stringify(zoom)}`);
  if (!(await click('.code-row.file', 'review.py'))) return [...errors, 'Python file absent from tree'];
  await page.waitForSelector('.code-source-line');
  const source = await page.$eval('.code-inspector', (el) => el.innerText);
  if (!source.includes('return 1') || !source.includes('abc123base')) errors.push('base source contents or revision missing');
  if (!(await page.$('.syntax-keyword'))) errors.push('source syntax not highlighted');
  const scale = await page.$eval('.pgraph canvas', (c) => c.__graphScale);
  await page.$eval('.inspector-body', (el) => el.dispatchEvent(new WheelEvent('wheel', { deltaY: 100, bubbles: true, cancelable: true })));
  await wait();
  if (await page.$eval('.pgraph canvas', (c) => c.__graphScale) !== scale) errors.push('source scrolling changed graph zoom');
  await click('.code-row.sym', 'review'); await wait();
  if (!(await page.$('.code-source-line.jump[data-line="3"]'))) errors.push('symbol did not highlight definition line');
  await click('.inspector-head button', 'Expand'); await wait();
  if (!(await page.$('.inspector-expanded'))) errors.push('inspector did not expand');
  await click('.inspector-head button', 'Restore graph'); await wait();
  const oldSize = await page.$eval('.code-main', (e) => e.style.getPropertyValue('--inspector-size'));
  await page.focus('[aria-label="Resize code inspector"]'); await page.keyboard.press('ArrowUp');
  if (await page.$eval('.code-main', (e) => e.style.getPropertyValue('--inspector-size')) === oldSize) errors.push('keyboard resize did not change inspector');
  await shot(page, 'code-source-inspector');
  await page.click('.code-source-line[data-line="3"] .line-number');
  await page.keyboard.down('Shift');
  await page.click('.code-source-line[data-line="4"] .line-number');
  await page.keyboard.up('Shift');
  await click('.code-selection button', 'Request a change'); await wait();
  await page.select('.code-agent-chooser select', 'a1');
  await click('.code-agent-chooser button', 'Open draft'); await wait();
  const sourceDraft = await page.$eval('.composer textarea', (e) => e.value);
  for (const needed of ['My existing instructions', 'src/review.py:3-4', 'return 1', 'ask what change I want before editing']) if (!sourceDraft.includes(needed)) errors.push(`source draft missing ${needed}`);
  if (await page.evaluate(() => window.__test.sends.length)) errors.push('source selection sent a message');
  await click('.nav-item', 'Code'); await wait();
  await page.waitForSelector('.pgraph canvas');
  await target('local');
  if (!(await click('.changed-file', 'src/review.py'))) return [...errors, 'changed-file list missing'];
  await page.waitForSelector('.code-diff-line');
  if (!(await page.$eval('.code-inspector', (e) => e.innerText.includes('return 42')))) errors.push('diff contents missing');
  if (!(await page.$('.diff-word-change'))) errors.push('modified words are not emphasized');
  await click('.diff-controls button', 'Next hunk');
  await click('.diff-controls button', 'Side by side');
  await page.waitForSelector('.code-diff-split');
  await click('.diff-controls button', 'Inline');
  await click('.diff-controls button', 'More context');
  await page.waitForFunction(() => window.__test.codeCalls.some((call) =>
    call.method === 'codeindex.file_diff' && call.more_context && call.comparison === 'working'));
  await shot(page, 'code-diff-inspector');
  await click('.diff-controls button', 'Delta');
  await page.waitForSelector('.code-inspector .xterm-rows');
  await wait();
  if (!(await page.$eval('.code-inspector', (e) => e.innerText.includes('return')))) errors.push('delta output missing');
  await page.waitForFunction(() => window.__test.codeCalls.some((call) => call.method === 'codeindex.file_diff' && call.render === 'delta'));
  await shot(page, 'code-diff-delta');
  await click('.diff-controls button', 'Delta'); await wait();
  await click('.changed-file', 'src/deleted.py'); await wait();
  await click('[aria-label="Code inspector tabs"] button', 'Source'); await wait();
  if (!(await page.$eval('.code-inspector', (e) => /missing|deleted/i.test(e.innerText)))) errors.push('deleted source not explained');
  await click('.changed-file', 'image.bin'); await wait();
  if (!(await page.$eval('.code-inspector', (e) => /binary/i.test(e.innerText)))) errors.push('binary diff not explained');
  await target('w1');
  await page.evaluate(() => { window.__test.slowSource = true; });
  await click('.code-row.file', 'review.py');
  await target('w2'); await click('.code-row.file', 'review.py');
  await new Promise((r) => setTimeout(r, 650));
  const switched = await page.$eval('.code-inspector', (e) => e.innerText);
  if (!switched.includes('working-tree:w2') || switched.includes('working-tree:w1')) errors.push('stale worktree source shown after rapid target switch');
  await page.evaluate(() => { window.__test.slowSource = false; });
  await target('w1'); await click('.changed-file', 'src/review.py'); await wait();
  await click('.changed-files button', 'Against base'); await wait();
  await click('.hunk-select', 'Select hunk'); await wait();
  if (!(await page.$('.code-selection'))) return [...errors, 'hunk selection missing'];
  await click('.code-selection button', 'Explain'); await wait();
  const agentSelect = await page.$('.code-agent-chooser select');
  if (!agentSelect) return [...errors, 'agent chooser missing'];
  await agentSelect.select('a1');
  await click('.code-agent-chooser button', 'Open draft'); await wait();
  await page.waitForSelector('.composer textarea');
  const handoff = await page.evaluate(() => ({ text: document.querySelector('.composer textarea')?.value, sends: window.__test.sends.length }));
  for (const needed of ['My existing instructions', 'src/review.py', 'Worktree: w1', 'Comparison base: abc123base', 'return 42']) if (!handoff.text?.includes(needed)) errors.push(`handoff context missing ${needed}`);
  if (handoff.sends) errors.push('context action sent without user confirmation');
  await shot(page, 'code-agent-draft');
  await click('.agent-list .list-item', 'otter'); await wait();
  if (await page.$eval('.composer textarea', (e) => e.value)) errors.push('code context leaked into peer agent draft');
  await click('.agent-list .list-item', 'lion'); await wait();
  if (!(await page.$eval('.composer textarea', (e) => e.value.includes('return 42')))) errors.push('code context lost when revisiting agent');
  return errors;
}
